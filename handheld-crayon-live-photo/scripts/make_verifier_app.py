#!/usr/bin/env python3
"""Wrap a PhotoKit command in a throwaway .app so macOS will grant access.

Why this exists
---------------
PhotoKit authorisation is a TCC decision. Two things silently break it:

  * running under a host that has no NSPhotoLibraryUsageDescription
    -> requestAuthorization returns Denied immediately, no prompt;
  * running from a bare CLI process
    -> the completion handler is queued on the main queue, which nobody
       is draining, so the call never returns.

The fix is to run the same command as the executable of a real app bundle
that declares the usage strings. macOS then shows the normal
"App wants to access Photos" prompt, and once granted the decision sticks
for that bundle.

Usage
    python3 make_verifier_app.py --out /tmp/LPVerify.app \
        -- python3 scripts/make_livephoto.py --video live.mp4 --out-dir pair/

    open -a /tmp/LPVerify.app          # grant access in the dialog
    cat /tmp/lpverify.log              # the wrapped command's output

Requirements: macOS. Uses /usr/bin/codesign (ad-hoc signature), which does
not need Xcode or the Command Line Tools.
"""
import argparse
import os
import shlex
import shutil
import subprocess
import sys

PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key><string>{bundle_id}</string>
    <key>CFBundleName</key><string>{name}</string>
    <key>CFBundleExecutable</key><string>run</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>NSPhotoLibraryUsageDescription</key><string>{usage}</string>
    <key>NSPhotoLibraryAddUsageDescription</key><string>{usage}</string>
</dict>
</plist>
"""

RUNNER = """#!/bin/sh
# generated by make_verifier_app.py
LOG={log}
: > "$LOG"
echo "+ {cmd}" >> "$LOG"
{cmd} >> "$LOG" 2>&1
echo "EXIT=$?" >> "$LOG"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="/tmp/LPVerify.app", help="app bundle path")
    ap.add_argument("--name", default="LivePhotoVerifier")
    ap.add_argument("--bundle-id", default="com.workbuddy.livephoto-verifier")
    ap.add_argument("--log", default="/tmp/lpverify.log")
    ap.add_argument("--usage", default="Import the generated Live Photo pair "
                                       "and verify it with PhotoKit.")
    ap.add_argument("--run", action="store_true", help="launch it right away")
    ap.add_argument("command", nargs=argparse.REMAINDER,
                    help="command to wrap (pass after --)")
    args = ap.parse_args()

    cmd = args.command
    while cmd and cmd[0] == "--":
        cmd = cmd[1:]
    if not cmd:
        ap.error("no command given (pass it after --)")

    app = os.path.abspath(args.out)
    macos = os.path.join(app, "Contents", "MacOS")
    if os.path.exists(app):
        shutil.rmtree(app)
    os.makedirs(macos)

    with open(os.path.join(app, "Contents", "Info.plist"), "w") as fh:
        fh.write(PLIST.format(bundle_id=args.bundle_id, name=args.name,
                              usage=args.usage))
    runner = os.path.join(macos, "run")
    with open(runner, "w") as fh:
        fh.write(RUNNER.format(log=args.log,
                               cmd=" ".join(shlex.quote(c) for c in cmd)))
    os.chmod(runner, 0o755)

    subprocess.run(["xattr", "-cr", app], check=False)
    subprocess.run(["/usr/bin/codesign", "--force", "--deep", "-s", "-", app],
                   check=False)

    print("app  :", app)
    print("log  :", args.log)
    print("run  : open -a", app)
    if args.run:
        subprocess.run(["open", "-a", app], check=False)
        print("launched; watch the log with:  tail -f", args.log)
    return 0


if __name__ == "__main__":
    sys.exit(main())
